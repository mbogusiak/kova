/// Host capabilities imported from Kova IDE (`kova:plugin/host`).
///
/// Every function here is a call into the sandbox host and is subject to the
/// permissions declared in `plugin.toml` (e.g. `editor_read`).
pub mod host {
    pub use crate::bindings::kova::plugin::host::{
        apply_editor_edit, get_editor_snapshot, log, register_command, register_tool_window,
    };
}

/// Exports a type implementing [`Guest`] as the plugin component entrypoint.
///
/// Invoke exactly once at the crate root of a `cdylib` plugin:
///
/// ```ignore
/// struct MyPlugin;
/// impl kova_plugin_rs::Guest for MyPlugin { /* ... */ }
/// kova_plugin_rs::export_plugin!(MyPlugin);
/// ```
#[macro_export]
macro_rules! export_plugin {
    ($ty:ident) => {
        // Component exports only exist on WASM; native builds keep the `Guest`
        // impl for unit tests without emitting unresolvable export symbols.
        #[cfg(target_family = "wasm")]
        #[doc(hidden)]
        #[allow(
            unsafe_code,
            unused_qualifications,
            clippy::all,
            clippy::pedantic,
            clippy::mem_forget,
            clippy::undocumented_unsafe_blocks,
            reason = "component export glue generated by wit-bindgen"
        )]
        mod __kova_plugin_export {
            use super::$ty;
            $crate::bindings::__export_kova_plugin_world!($ty);
        }
    };
}

/// Name of this crate as declared in its `Cargo.toml`.
pub const CRATE_NAME: &str = env!("CARGO_PKG_NAME");

/// WIT contract version targeted by this SDK (must match `api_version` in `plugin.toml`).
pub const API_VERSION: &str = "0.1.0";

#[cfg(test)]
mod tests {
    use super::{API_VERSION, CRATE_NAME};

    #[test]
    fn crate_name_matches_manifest() {
        assert_eq!(CRATE_NAME, "kova_plugin_rs");
    }

    #[test]
    fn inherits_workspace_license() {
        assert_eq!(env!("CARGO_PKG_LICENSE"), "MIT OR Apache-2.0");
    }

    #[test]
    fn targets_wit_api_0_1() {
        assert_eq!(API_VERSION, "0.1.0");
        let wit = include_str!("../../../crates/kova_plugin_host/wit/kova-plugin.wit");
        assert!(wit.starts_with("package kova:plugin@0.1.0;"));
    }
}
