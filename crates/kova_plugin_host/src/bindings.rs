/// Upper bound on declarative widget nodes a plugin may emit in a single tree.
pub const MAX_WIDGET_NODES: usize = 10_000;

/// Validates that a WIT [`WidgetTree`] returned by a plugin is structurally sound
/// before forwarding it to the native GPUI renderer (`kova_ui`).
///
/// Checks:
/// - non-empty node list and bounded node count (`<= MAX_WIDGET_NODES`),
/// - valid `root` and `children` indices,
/// - cycle-freedom (DAG/tree invariant),
/// - `Split` ratio within `0..=100`.
///
/// # Errors
///
/// Returns [`PluginHostError::InvalidWidgetTree`] if any invariant is violated.
pub fn validate_widget_tree(plugin_id: &str, tree: &WidgetTree) -> Result<(), PluginHostError> {
    let err = |reason: String| PluginHostError::InvalidWidgetTree {
        plugin_id: plugin_id.to_owned(),
        reason,
    };

    if tree.nodes.is_empty() {
        return Err(err("widget tree must contain at least one node".to_owned()));
    }
    if tree.nodes.len() > MAX_WIDGET_NODES {
        return Err(err(format!(
            "widget tree has {} nodes, exceeding limit of {MAX_WIDGET_NODES}",
            tree.nodes.len()
        )));
    }

    let root_idx = usize::try_from(tree.root)
        .map_err(|_| err("root index does not fit into usize".to_owned()))?;
    if root_idx >= tree.nodes.len() {
        return Err(err(format!(
            "root index {root_idx} out of bounds for {} nodes",
            tree.nodes.len()
        )));
    }

    let mut seen_ids = HashSet::with_capacity(tree.nodes.len());
    for (idx, node) in tree.nodes.iter().enumerate() {
        if node.id.is_empty() {
            return Err(err(format!("widget node at index {idx} has empty `id`")));
        }
        if !seen_ids.insert(node.id.as_str()) {
            return Err(err(format!("duplicate widget id `{}`", node.id)));
        }
        if let WidgetKind::Split(ref split) = node.kind
            && split.ratio_percent > 100
        {
            return Err(err(format!(
                "split widget `{}` ratio_percent {} exceeds 100",
                node.id, split.ratio_percent
            )));
        }
        for &child in &node.children {
            let child_idx = usize::try_from(child)
                .map_err(|_| err("child index does not fit into usize".to_owned()))?;
            if child_idx >= tree.nodes.len() {
                return Err(err(format!(
                    "widget `{}` references out-of-bounds child index {child_idx}",
                    node.id
                )));
            }
        }
    }

    // Iterative 3-color DFS to verify acyclicity without risking stack overflow.
    // 0 = unvisited, 1 = on current path, 2 = completed.
    let mut state = vec![0_u8; tree.nodes.len()];
    let mut stack: Vec<(usize, bool)> = vec![(root_idx, false)];
    while let Some((idx, exiting)) = stack.pop() {
        if exiting {
            state[idx] = 2;
            continue;
        }
        match state[idx] {
            1 => {
                return Err(err(format!(
                    "cycle detected at widget `{}` (index {idx})",
                    tree.nodes[idx].id
                )));
            }
            2 => continue,
            _ => {}
        }
        state[idx] = 1;
        stack.push((idx, true));
        for &child in &tree.nodes[idx].children {
            let child_idx = child as usize;
            if state[child_idx] == 1 {
                return Err(err(format!(
                    "cycle detected between `{}` and `{}`",
                    tree.nodes[idx].id, tree.nodes[child_idx].id
                )));
            }
            if state[child_idx] == 0 {
                stack.push((child_idx, false));
            }
        }
    }

    Ok(())
}
